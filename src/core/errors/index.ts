export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

export interface LauncherErrorDetails {
  readonly [key: string]: unknown;
}

export class LauncherError extends Error {
  readonly code: ErrorCode;
  readonly details: LauncherErrorDetails;

  constructor(code: ErrorCode, message: string, details: LauncherErrorDetails = {}) {
    super(message);
    this.name = "LauncherError";
    this.code = code;
    this.details = details;
  }

  static isLauncherError(err: unknown): err is LauncherError {
    return err instanceof LauncherError;
  }
}
